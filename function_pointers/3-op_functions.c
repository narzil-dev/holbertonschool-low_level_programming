
#include "3-calc.h"

/**
 * op_add - Additionne deux entiers
 * @a: Premier entier
 * @b: Deuxième entier
 *
 * Return: Somme des deux entiers
 */
int op_add(int a, int b)
{
	return (a + b);
}

/**
 * op_sub - Soustrait deux entiers
 * @a: Premier entier
 * @b: Deuxième entier
 *
 * Return: Différence des deux entiers
 */
int op_sub(int a, int b)
{
	return (a - b);
}

/**
 * op_mul - Multiplie deux entiers
 * @a: Premier entier
 * @b: Deuxième entier
 *
 * Return: Produit des deux entiers
 */
int op_mul(int a, int b)
{
	return (a * b);
}

/**
 * op_div - Divise deux entiers
 * @a: Premier entier
 * @b: Deuxième entier
 *
 * Return: Quotient des deux entiers
 */
int op_div(int a, int b)
{
	return (a / b);
}

/**
 * op_mod - Calcule le reste d'une division
 * @a: Premier entier
 * @b: Deuxième entier
 *
 * Return: Reste de la division
 */
int op_mod(int a, int b)
{
	return (a % b);
}
